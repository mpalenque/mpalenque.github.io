const EN_COPY = {};
const i18nNodes = Array.from(document.querySelectorAll("[data-i18n]"));
const i18nHtmlNodes = Array.from(document.querySelectorAll("[data-i18n-html]"));
const langButtons = Array.from(document.querySelectorAll("[data-set-lang]"));

for (const el of i18nNodes) {
  EN_COPY[el.dataset.i18n] = el.textContent;
}
for (const el of i18nHtmlNodes) {
  EN_COPY[el.dataset.i18nHtml] = el.innerHTML;
}
EN_COPY.metaTitle = document.title;
EN_COPY.metaDescription =
  document.querySelector('meta[name="description"]')?.getAttribute("content") || "";
EN_COPY.skipLink = document.querySelector(".skip-link")?.textContent || "";
EN_COPY.navLabel = document.querySelector(".nav")?.getAttribute("aria-label") || "";
EN_COPY.langGroupLabel = document.querySelector(".lang-switch")?.getAttribute("aria-label") || "";
EN_COPY.heroScrollLabel =
  document.querySelector(".hero-bottom a")?.getAttribute("aria-label") || "";
EN_COPY.contextVideoAria =
  document.querySelector(".video-preview")?.getAttribute("aria-label") || "";
EN_COPY.contextVideoTitle =
  document.querySelector(".video-preview")?.dataset.title || "";

function applyLanguage(lang) {
  const target = lang === "es" ? "es" : "en";
  const dict = target === "es" ? ES_COPY : EN_COPY;

  document.documentElement.lang = target;
  document.title = dict.metaTitle;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict.metaDescription) metaDesc.setAttribute("content", dict.metaDescription);

  const skip = document.querySelector(".skip-link");
  if (skip && dict.skipLink) skip.textContent = dict.skipLink;

  const nav = document.querySelector(".nav");
  if (nav && dict.navLabel) nav.setAttribute("aria-label", dict.navLabel);

  const langGroup = document.querySelector(".lang-switch");
  if (langGroup && dict.langGroupLabel) langGroup.setAttribute("aria-label", dict.langGroupLabel);

  const scrollLink = document.querySelector(".hero-bottom a");
  if (scrollLink && dict.heroScrollLabel) scrollLink.setAttribute("aria-label", dict.heroScrollLabel);

  const previewBtn = document.querySelector(".video-preview");
  if (previewBtn) {
    if (dict.contextVideoAria) previewBtn.setAttribute("aria-label", dict.contextVideoAria);
    if (dict.contextVideoTitle) previewBtn.dataset.title = dict.contextVideoTitle;
  }

  for (const el of i18nNodes) {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.textContent = dict[key];
  }
  for (const el of i18nHtmlNodes) {
    const key = el.dataset.i18nHtml;
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  }

  for (const btn of langButtons) {
    btn.setAttribute("aria-pressed", String(btn.dataset.setLang === target));
  }

  try {
    localStorage.setItem("course_lang", target);
  } catch {
    // Ignore storage failures in restricted contexts
  }
}

for (const btn of langButtons) {
  btn.addEventListener("click", () => applyLanguage(btn.dataset.setLang));
}

(function initLanguage() {
  let initial = "en";
  const params = new URLSearchParams(window.location.search);
  const urlLang = params.get("lang");
  if (urlLang === "es" || urlLang === "en") {
    initial = urlLang;
  } else {
    try {
      const saved = localStorage.getItem("course_lang");
      if (saved === "es" || saved === "en") initial = saved;
    } catch {
      // Default to English
    }
  }
  if (initial === "es") applyLanguage("es");
})();

/* Video preview & native <dialog> player (matching curso.js contract) */
const previews = Array.from(document.querySelectorAll(".video-preview"));
const dialog = document.querySelector(".video-dialog");
const fullVideo = dialog?.querySelector(".full-video");
const dialogTitle = dialog?.querySelector(".dialog-bar .label");
const closeButton = dialog?.querySelector(".close-video");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
const finePointer = window.matchMedia("(hover: hover) and (pointer: fine)");
let activePreview = null;

function loadVideo(video) {
  if (video && !video.getAttribute("src") && video.dataset.src) {
    video.src = video.dataset.src;
  }
}

function stopPreview(preview) {
  const video = preview.querySelector("video");
  if (video) video.pause();
  preview.classList.remove("is-playing");
}

async function playPreview(preview) {
  if (reducedMotion.matches || dialog?.open || document.hidden) return;
  for (const other of previews) {
    if (other !== preview) stopPreview(other);
  }
  const video = preview.querySelector("video");
  if (!video) return;
  loadVideo(video);
  video.muted = true;
  try {
    await video.play();
    if (!dialog?.open && (preview.matches(":hover") || preview.matches(":focus-visible"))) {
      preview.classList.add("is-playing");
    } else {
      stopPreview(preview);
    }
  } catch {
    stopPreview(preview);
  }
}

for (const preview of previews) {
  preview.addEventListener("pointerenter", () => {
    if (finePointer.matches) playPreview(preview);
  });
  preview.addEventListener("pointerleave", () => stopPreview(preview));
  preview.addEventListener("focus", () => playPreview(preview));
  preview.addEventListener("blur", () => stopPreview(preview));
  preview.addEventListener("click", () => {
    if (!dialog || !fullVideo || !closeButton) return;
    for (const other of previews) stopPreview(other);
    activePreview = preview;
    const video = preview.querySelector("video");
    if (dialogTitle && preview.dataset.title) {
      dialogTitle.textContent = preview.dataset.title;
    }
    fullVideo.src = video?.dataset.src || "";
    fullVideo.poster = video?.poster || "";
    fullVideo.muted = true;
    dialog.showModal();
    document.body.classList.add("modal-open");
    fullVideo.play().catch(() => {});
    closeButton.focus();
  });
}

if (dialog && fullVideo && closeButton) {
  closeButton.addEventListener("click", () => dialog.close());
  dialog.addEventListener("click", (event) => {
    if (event.target !== dialog) return;
    const bounds = dialog.getBoundingClientRect();
    if (
      event.clientX < bounds.left ||
      event.clientX > bounds.right ||
      event.clientY < bounds.top ||
      event.clientY > bounds.bottom
    ) {
      dialog.close();
    }
  });
  dialog.addEventListener("close", () => {
    fullVideo.pause();
    fullVideo.removeAttribute("src");
    fullVideo.load();
    document.body.classList.remove("modal-open");
    activePreview?.focus({ preventScroll: true });
  });
}

document.addEventListener("visibilitychange", () => {
  if (document.hidden) {
    for (const preview of previews) stopPreview(preview);
    fullVideo?.pause();
  }
});

if (previews.length > 0 && "IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (!entry.isIntersecting) stopPreview(entry.target);
    }
  });
  for (const preview of previews) observer.observe(preview);
}

reducedMotion.addEventListener("change", () => {
  if (reducedMotion.matches) {
    for (const preview of previews) stopPreview(preview);
  }
});

/* Clean Print / PDF export: expand all module accordions during print */
const allDetails = Array.from(document.querySelectorAll("details"));
let closedBeforePrint = [];

function expandDetailsForPrint() {
  closedBeforePrint = allDetails.filter((item) => !item.open);
  for (const item of closedBeforePrint) item.open = true;
}

function restoreDetailsAfterPrint() {
  for (const item of closedBeforePrint) item.open = false;
  closedBeforePrint = [];
}

window.addEventListener("beforeprint", expandDetailsForPrint);
window.addEventListener("afterprint", restoreDetailsAfterPrint);

const printTrigger = document.querySelector("[data-print-pdf]");
if (printTrigger) {
  printTrigger.addEventListener("click", () => {
    expandDetailsForPrint();
    window.print();
  });
}
